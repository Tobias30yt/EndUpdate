"""Import Imagegen originals; nearest-neighbour resize only. All assets are namespaced."""
from pathlib import Path
from PIL import Image, ImageDraw
import json, shutil

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'resourcepack/assets/endupdate'
manifest = json.loads((ROOT/'tools/trader-assets.json').read_text('utf-8'))

def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2)+'\n', 'utf-8')

def item(name, model):
    write(ASSETS/f'items/{name}.json', {'model': {'type':'minecraft:model', 'model':'endupdate:'+model}})

preview = Image.new('RGB', (640, 320), '#302735')
draw = ImageDraw.Draw(preview)
for i, (name, entry) in enumerate(manifest.items()):
    original = ROOT/f'art/generated/traders/{name}.png'
    original.parent.mkdir(parents=True, exist_ok=True)
    if not original.exists(): shutil.copyfile(entry['path'], original)
    small = Image.open(original).convert('RGBA').resize((32,32) if name=='villager' else (16,16), Image.Resampling.NEAREST)
    if name=='villager':
        # ItemDisplay JSON geometry is baked from atlas sprites, not entity skins.
        # Keep this with the model's block accents; mixing item/block atlases is invalid.
        target=ASSETS/'textures/block/mithryl_villager.png'
        (ASSETS/'textures/entity/mithryl_villager.png').unlink(missing_ok=True)
    elif entry['transparent']:
        target=ASSETS/f'textures/item/mithryl_{name}.png'
        write(ASSETS/f'models/item/mithryl_{name}.json', {'parent':'minecraft:item/handheld' if name=='bloom_wand' else 'minecraft:item/generated', 'textures':{'layer0':f'endupdate:item/mithryl_{name}'}})
        item('mithryl_'+name, 'item/mithryl_'+name)
    else:
        target=ASSETS/f'textures/block/{name}.png'
        top='end_planks' if name=='grove_bench' else 'mithryl_block'
        write(ASSETS/f'models/block/{name}.json', {'parent':'minecraft:block/cube_bottom_top','textures':{
            'side':f'endupdate:block/{name}','top':f'endupdate:block/{top}','bottom':'endupdate:block/end_planks'}})
        item(name,'block/'+name)
    target.parent.mkdir(parents=True, exist_ok=True);small.save(target)
    icon=small.resize((112,112),Image.Resampling.NEAREST)
    x,y=(i%4)*160,(i//4)*160
    preview.paste(icon,(x+24,y+8),icon);draw.text((x+10,y+132),name,fill='#f1d5e7')

