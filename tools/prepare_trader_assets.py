vanilla['ingot']={k:v for k,v in manifest['ingot'].items() if k!='transparent'}
write(ROOT/'tools/vanilla-assets.json',vanilla)

def cube(lo,hi,uv,texture='skin',front=None):
    faces={side:{'uv':uv,'texture':'#'+texture} for side in ('north','south','east','west','up','down')}
    if front is not None: faces['south']={'uv':front,'texture':'#skin'}
    return {'from':lo,'to':hi,'faces':faces}

